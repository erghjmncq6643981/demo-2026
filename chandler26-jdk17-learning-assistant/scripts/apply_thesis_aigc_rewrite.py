NS_W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
NS_XML = "{http://www.w3.org/XML/1998/namespace}space"

KEEP_TAGS = {NS_W + "pPr", NS_W + "bookmarkStart", NS_W + "bookmarkEnd"}


def set_text(p_el, text):
    """清空段落内容并写入新文本，保留 pPr / 书签 / 首个 run 的 rPr。"""
    rPr = None
    for r in p_el.findall(NS_W + "r"):
        rp = r.find(NS_W + "rPr")
        if rp is not None:
            rPr = copy.deepcopy(rp)
            break

    for child in list(p_el):
        if child.tag not in KEEP_TAGS:
            p_el.remove(child)

    run = OxmlElement("w:r")
    if rPr is not None:
        run.append(rPr)
    t = OxmlElement("w:t")
    t.set(NS_XML, "preserve")
    t.text = text
    run.append(t)
    p_el.append(run)


def clone_after(p_el):
    """在 p_el 之后插入一个同样式的新段落（文本待设）。"""
    new_el = copy.deepcopy(p_el)
    p_el.addnext(new_el)
    return new_el


def delete_p(p_el):
    parent = p_el.getparent()
    parent.remove(p_el)


