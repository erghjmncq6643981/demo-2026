export function createRuminationElements(root = document) {
  const $ = (id) => (root.getElementById ? root.getElementById(id) : root.querySelector(`#${id}`))
  const ruminationWordbookSelect = $('ruminationWordbookSelect') || $('articleWordbookSelect')
  const ruminationToolbar = $('ruminationToolbar') || $('articleStudyToolbar')
  const toggleRuminationFocusModeBtn = $('toggleRuminationFocusModeBtn') || $('toggleArticleFocusModeBtn')
  return {
    ruminationView: $('ruminationView') || $('articleStudyView'),
    ruminationWordbookSelect,
    articleWordbookSelect: ruminationWordbookSelect,
    ruminationToolbar,
    articleStudyToolbar: ruminationToolbar,
    toggleRuminationFocusModeBtn,
    toggleArticleFocusModeBtn: toggleRuminationFocusModeBtn,
    ruminationPracticeModal: $('ruminationPracticeModal'),
  }
}

export const createReadingElements = createRuminationElements

